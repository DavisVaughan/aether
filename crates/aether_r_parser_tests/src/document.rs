use std::fmt::Write as _;

/// One corpus test file
///
/// Covers both human created input files and generated snapshot files. The
/// only difference is that snapshot files have non empty `generated` cells.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct Document {
    pub tests: Vec<Section>,
}

/// One `##` heading and everything under it
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct Section {
    pub name: String,
    pub markers: Markers,

    pub elements: Vec<Element>,
}

#[derive(Debug, Clone, PartialEq, Eq)]
pub enum Element {
    /// Copied verbatim into the snapshot, never parsed
    Prose(String),
    Block(Block),
}

/// One ```` ```r ```` cell and the cells generated from it
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct Block {
    pub source: String,
    pub generated: Vec<Cell>,
}

/// A cell the harness produces, in snapshot files only
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum Cell {
    /// The typed AST view, which is the one worth reviewing
    Cst(String),
    /// The raw `SyntaxNode` view, opt-in per block
    CstRaw(String),
    /// Rendered diagnostics, omitted entirely when there are none
    Diagnostics(String),
    /// The whole output for a `[pending]` block
    Pending,
}

bitflags::bitflags! {
    #[derive(Debug, Clone, Copy, PartialEq, Eq)]
    pub struct Markers: u8 {
        const PENDING = 1 << 0;
        const ERROR = 1 << 1;
        const DEVIATION = 1 << 2;
    }
}

#[derive(Debug, Clone, PartialEq, Eq)]
pub struct DocumentError {
    pub line: usize,
    pub message: String,
}

const PENDING_CELL: &str = "*Not yet supported.*";

impl std::fmt::Display for DocumentError {
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        write!(f, "line {}: {}", self.line, self.message)
    }
}

impl std::error::Error for DocumentError {}

impl Markers {
    fn parse(text: &str, line: usize) -> Result<Self, DocumentError> {
        let mut markers = Markers::empty();

        for name in text.split(',') {
            let marker = match name.trim() {
                "pending" => Markers::PENDING,
                "error" => Markers::ERROR,
                "deviation" => Markers::DEVIATION,
                other => {
                    return Err(DocumentError {
                        line,
                        message: format!(
                            "unknown marker `{other}`, expected `pending`, `error` or `deviation`"
                        ),
                    });
                }
            };
            markers |= marker;
        }

        Ok(markers)
    }

    fn render(self) -> String {
        let mut names = Vec::new();
        for (marker, name) in [
            (Markers::PENDING, "pending"),
            (Markers::ERROR, "error"),
            (Markers::DEVIATION, "deviation"),
        ] {
            if self.contains(marker) {
                names.push(name);
            }
        }

        if names.is_empty() {
            String::new()
        } else {
            format!(" [{}]", names.join(", "))
        }
    }
}

impl Section {
    pub fn blocks(&self) -> impl DoubleEndedIterator<Item = &Block> {
        self.elements.iter().filter_map(|element| match element {
            Element::Block(block) => Some(block),
            Element::Prose(_) => None,
        })
    }

    pub fn blocks_mut(&mut self) -> impl DoubleEndedIterator<Item = &mut Block> {
        self.elements
            .iter_mut()
            .filter_map(|element| match element {
                Element::Block(block) => Some(block),
                Element::Prose(_) => None,
            })
    }
}

impl Document {
    pub fn parse(text: &str) -> Result<Document, DocumentError> {
        Parser::new(text).parse()
    }

    /// Renders the snapshot flavour of this document
    ///
    /// `source` names the input file the snapshot came from, relative to the
    /// corpus root.
    pub fn render_snapshot(&self, source: &str) -> String {
        let mut out = String::new();
        writeln!(out, "<!-- Generated by `xtask accept`. Do not edit.").unwrap();
        writeln!(out, "     Source: {source} -->").unwrap();

        for test in &self.tests {
            writeln!(out, "\n## {}{}", test.name, test.markers.render()).unwrap();

            for element in &test.elements {
                match element {
                    Element::Prose(prose) => writeln!(out, "\n{prose}").unwrap(),
                    Element::Block(block) => render_block(&mut out, block),
                }
            }
        }

        out
    }

    /// The heading sequence, for the pairing invariant
    ///
    /// Prose is deliberately absent: it is echoed rather than derived, so an
    /// edit to it is an ordinary content diff that `just accept` fixes.
    pub fn shape(&self) -> Vec<(&str, Markers, usize)> {
        self.tests
            .iter()
            .map(|test| (test.name.as_str(), test.markers, test.blocks().count()))
            .collect()
    }
}

fn render_block(out: &mut String, block: &Block) {
    render_fence(out, "r", &block.source);

    for cell in &block.generated {
        match cell {
            Cell::Cst(content) => render_fence(out, "cst", content),
            Cell::CstRaw(content) => render_fence(out, "cst-raw", content),
            Cell::Diagnostics(content) => render_fence(out, "diagnostics", content),
            Cell::Pending => {
                out.push('\n');
                out.push_str(PENDING_CELL);
                out.push('\n');
            }
        }
    }
}

fn render_fence(out: &mut String, language: &str, content: &str) {
    out.push('\n');
    out.push_str("```");
    out.push_str(language);
    out.push('\n');
    out.push_str(content);
    // A cell whose content does not end its line would swallow the fence
    if !content.is_empty() && !content.ends_with('\n') {
        out.push('\n');
    }
    out.push_str("```\n");
}

struct Parser<'src> {
    lines: Vec<&'src str>,
    index: usize,
    tests: Vec<Section>,
    prose: Vec<&'src str>,
}

impl<'src> Parser<'src> {
    fn new(text: &'src str) -> Self {
        // `split_inclusive` keeps each line's terminator, so a file that does
        // not end in a newline is not silently given one
        let lines = text.split_inclusive('\n').collect();

        Self {
            lines,
            index: 0,
            tests: Vec::new(),
            prose: Vec::new(),
        }
    }

    fn parse(mut self) -> Result<Document, DocumentError> {
        while let Some(line) = self.next_line() {
            let trimmed = trim_newline(line);

            if let Some(heading) = trimmed.strip_prefix("## ") {
                self.finish_prose()?;
                let (name, markers) = parse_heading(heading, self.index)?;
                self.push_test(name, markers)?;
            } else if let Some(language) = fence_language(trimmed) {
                let content = self.read_fenced_content()?;
                self.push_cell(language, content)?;
            } else if trimmed == PENDING_CELL {
                self.push_generated(Cell::Pending)?;
            } else if self.tests.is_empty() && trimmed.starts_with("<!--") {
                self.skip_banner(trimmed);
            } else {
                self.prose.push(line);
            }
        }

        self.finish_prose()?;

        for test in &self.tests {
            if test.blocks().next().is_none() {
                return Err(DocumentError {
                    line: self.lines.len(),
                    message: format!("test `{}` has no ```r block", test.name),
                });
            }
        }

        Ok(Document { tests: self.tests })
    }

    fn next_line(&mut self) -> Option<&'src str> {
        let line = self.lines.get(self.index).copied();
        self.index += 1;
        line
    }

    fn skip_banner(&mut self, opening: &str) {
        if opening.ends_with("-->") {
            return;
        }

        while let Some(line) = self.next_line() {
            if trim_newline(line).ends_with("-->") {
                return;
            }
        }
    }

    fn read_fenced_content(&mut self) -> Result<String, DocumentError> {
        let opened = self.index;
        let mut content = String::new();

        while let Some(line) = self.next_line() {
            if trim_newline(line) == "```" {
                return Ok(content);
            }
            content.push_str(line);
        }

        Err(DocumentError {
            line: opened,
            message: "unterminated fenced cell".to_string(),
        })
    }

    fn push_test(&mut self, name: String, markers: Markers) -> Result<(), DocumentError> {
        if self.tests.iter().any(|test| test.name == name) {
            return Err(DocumentError {
                line: self.index,
                message: format!(
                    "duplicate test name `{name}`; names address tests in `MANIFEST.toml` and must be unique within a file"
                ),
            });
        }

        self.tests.push(Section {
            name,
            markers,
            elements: Vec::new(),
        });

        Ok(())
    }

    fn push_cell(&mut self, language: &str, content: String) -> Result<(), DocumentError> {
        self.finish_prose()?;

        if language == "r" {
            let block = Block {
                source: content,
                generated: Vec::new(),
            };
            return self.push_element(Element::Block(block));
        }

        let cell = match language {
            "cst" => Cell::Cst(content),
            "cst-raw" => Cell::CstRaw(content),
            "diagnostics" => Cell::Diagnostics(content),
            other => {
                return Err(DocumentError {
                    line: self.index,
                    message: format!(
                        "unknown cell language `{other}`, expected `r`, `cst`, `cst-raw` or `diagnostics`"
                    ),
                });
            }
        };

        self.push_generated(cell)
    }

    fn push_generated(&mut self, cell: Cell) -> Result<(), DocumentError> {
        self.finish_prose()?;

        let line = self.index;
        let block = self
            .tests
            .last_mut()
            .and_then(|test| test.blocks_mut().next_back());

        match block {
            Some(block) => {
                block.generated.push(cell);
                Ok(())
            }
            None => Err(DocumentError {
                line,
                message: "generated cell with no ```r block before it".to_string(),
            }),
        }
    }

    fn push_element(&mut self, element: Element) -> Result<(), DocumentError> {
        match self.tests.last_mut() {
            Some(test) => {
                test.elements.push(element);
                Ok(())
            }
            None => Err(DocumentError {
                line: self.index,
                message: "content before the first `## ` heading".to_string(),
            }),
        }
    }

    /// Flushes accumulated prose, dropping its boundary blank lines
    ///
    /// The trim is what makes rendering idempotent: loosely spaced input
    /// converges after one `just accept` instead of gaining a blank line on
    /// every pass.
    fn finish_prose(&mut self) -> Result<(), DocumentError> {
        let lines = std::mem::take(&mut self.prose);
        let prose = lines.concat();
        let prose = prose.trim_matches('\n');

        if prose.is_empty() {
            return Ok(());
        }

        self.push_element(Element::Prose(prose.to_string()))
    }
}

fn parse_heading(heading: &str, line: usize) -> Result<(String, Markers), DocumentError> {
    let heading = heading.trim();

    // Markers are the trailing bracketed group, so a name may itself contain
    // brackets — `Unsupported Subset2 With `]]` Over Multiple Lines` does
    let Some(open) = heading.strip_suffix(']').and_then(|rest| rest.rfind('[')) else {
        return Ok((heading.to_string(), Markers::empty()));
    };

    let inside = &heading[open + 1..heading.len() - 1];
    if inside.contains('[') || inside.contains(']') {
        return Ok((heading.to_string(), Markers::empty()));
    }

    let markers = Markers::parse(inside, line)?;
    Ok((heading[..open].trim().to_string(), markers))
}

fn fence_language(line: &str) -> Option<&str> {
    let language = line.strip_prefix("```")?;

    if language.is_empty() || language.contains(' ') {
        None
    } else {
        Some(language)
    }
}

fn trim_newline(line: &str) -> &str {
    line.trim_end_matches('\n').trim_end_matches('\r')
}

